create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '',
  avatar_url text,
  phone text,
  rating_avg numeric(3, 2) not null default 0 check (rating_avg between 0 and 5),
  rating_count integer not null default 0 check (rating_count >= 0),
  location extensions.geography (point, 4326),
  neighborhood text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.categories (
  id smallint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  icon text not null default '',
  sort_order smallint not null default 0
);

create table public.needs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  title text not null check (char_length(title) between 3 and 120),
  description text not null check (char_length(description) between 10 and 2000),
  category_id smallint not null references public.categories (id),
  deal_type public.deal_type not null,
  budget_or_offer_details text,
  start_date date not null,
  end_date date,
  status public.need_status not null default 'open',
  reference_image_url text,
  location extensions.geography (point, 4326),
  address_label text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint needs_dates_valid check (end_date is null or end_date >= start_date)
);

create table public.offers (
  id uuid primary key default gen_random_uuid(),
  need_id uuid not null references public.needs (id) on delete cascade,
  supplier_id uuid not null references public.profiles (id) on delete cascade,
  price_offered numeric(12, 2) check (price_offered >= 0),
  swap_offered_details text,
  conditions text,
  item_photo_url text,
  status public.offer_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint offers_need_supplier_unique unique (need_id, supplier_id)
);

create table public.chat_messages (
  id uuid primary key default gen_random_uuid(),
  need_id uuid not null references public.needs (id) on delete cascade,
  offer_id uuid references public.offers (id) on delete cascade,
  sender_id uuid not null references public.profiles (id) on delete cascade,
  receiver_id uuid not null references public.profiles (id) on delete cascade,
  message text not null check (char_length(message) between 1 and 2000),
  created_at timestamptz not null default now(),
  constraint chat_messages_participants_differ check (sender_id <> receiver_id)
);

create table public.reviews (
  id uuid primary key default gen_random_uuid(),
  need_id uuid not null references public.needs (id) on delete cascade,
  reviewer_id uuid not null references public.profiles (id) on delete cascade,
  reviewee_id uuid not null references public.profiles (id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  comment text check (char_length(comment) <= 500),
  created_at timestamptz not null default now(),
  constraint reviews_participants_differ check (reviewer_id <> reviewee_id),
  constraint reviews_need_reviewer_reviewee_unique unique (need_id, reviewer_id, reviewee_id)
);

create index needs_status_created_at_idx on public.needs (status, created_at desc);
create index needs_category_id_idx on public.needs (category_id);
create index needs_deal_type_idx on public.needs (deal_type);
create index needs_user_id_idx on public.needs (user_id);
create index needs_location_gist_idx on public.needs using gist (location);

create index offers_need_id_status_idx on public.offers (need_id, status);
create index offers_supplier_id_idx on public.offers (supplier_id);

create index chat_messages_need_id_created_at_idx on public.chat_messages (need_id, created_at);
create index reviews_reviewee_id_idx on public.reviews (reviewee_id);
